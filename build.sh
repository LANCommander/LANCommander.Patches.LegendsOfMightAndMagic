#!/bin/sh
# Builds, with clang for the MSVC target (lld-link, the static CRT):
#   build/dinput.dll                                                   standalone patch (dinput.dll proxy)
#   build/lommpatch.asi                                                the same patches as an ASI plugin (ASI loader)
#   build/LANCommander.Interposer.Plugin.LegendsOfMightAndMagic.dll    LANCommander Interposer plugin (same patches)
# The dinput.dll and the ASI have the LANCommander Interposer (the DirectInput fix, voice chat, FastDL) linked in: its
# static library, LANCommander.Interposer.Static, is MSVC C++, hence the MSVC target. The plugin runs in the
# Interposer that loads it.
#
# Needs (from MSYS2's bash, or Git Bash):
# - clang and lld-link (LLVM; MSYS2: pacman -S mingw-w64-clang-x86_64-clang mingw-w64-clang-x86_64-lld)
# - Visual Studio 2022 or later with the C++ x86 tools and a Windows 10/11 SDK (found with vswhere), unless INCLUDE
#   and LIB are set already (a Developer Command Prompt for x86)
# - the Interposer (INTERPOSER_DIR, default third_party/LANCommander.Interposer) built with its windows-x86 preset:
#   cmake --preset windows-x86 && cmake --build --preset windows-x86-release --target LANCommander.Interposer.Static
#   (INTERPOSER=0 skips the dinput.dll and the ASI, for a quick build of the plugin alone)
# LM_VERSION=v1.2.3 sets the version the patch logs (default "dev").
set -e
cd "$(dirname "$0")"
OUT=build
mkdir -p $OUT
PATH="/c/msys64/clang64/bin:/c/Program Files/LLVM/bin:$PATH"

# MSVC and the Windows SDK, x86
if [ -z "$INCLUDE" ] || [ -z "$LIB" ]; then
    VS=$("/c/Program Files (x86)/Microsoft Visual Studio/Installer/vswhere.exe" -latest -products '*' \
         -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath | tr -d '\r')
    MSVC="$VS/VC/Tools/MSVC/$(tr -d '\r\n' < "$VS/VC/Auxiliary/Build/Microsoft.VCToolsVersion.default.txt")"
    SDK="C:/Program Files (x86)/Windows Kits/10"
    SDKV=$(ls "$SDK/Include" | grep '^10\.' | sort -V | tail -1)
    export INCLUDE="$MSVC/include;$SDK/Include/$SDKV/ucrt;$SDK/Include/$SDKV/um;$SDK/Include/$SDKV/shared"
    export LIB="$MSVC/lib/x86;$SDK/Lib/$SDKV/ucrt/x86;$SDK/Lib/$SDKV/um/x86"
fi

CFLAGS="--target=i686-pc-windows-msvc -fms-runtime-lib=static -O2 -Wall -Wextra -Wno-unused-parameter
    -Wno-missing-field-initializers -D_CRT_SECURE_NO_WARNINGS -D_WINSOCK_DEPRECATED_NO_WARNINGS
    -DLM_VERSION=\"${LM_VERSION:-dev}\""
# the Voice panel's background, built into the DLLs (voice_menu.c)
{
    echo '/* generated by build.sh from dist/voice options.png */'
    echo 'const unsigned char lm_voice_bg_png[] = {'
    od -An -v -tx1 "dist/voice options.png" | sed 's/ *\([0-9a-f][0-9a-f]\)/0x\1,/g'
    echo '};'
    echo 'const unsigned lm_voice_bg_png_size = sizeof lm_voice_bg_png;'
} > $OUT/voice_bg.c
CORE="$OUT/voice_bg.c src/lommpatch.c src/iat.c src/paths.c src/modules.c src/crashlog.c src/saves.c src/registry.c src/settings.c src/input.c
    src/widescreen.c src/window.c src/ui.c src/framerate.c src/menufast.c src/voice.c src/voice_menu.c src/voice_keys.c src/voice_game.c src/voice_net.c src/voice_server.c src/voice_server_win.c
    src/fastdl.c src/presence.c src/interposer_config.c"
LDFLAGS="-dll -opt:ref -opt:icf"
SYSLIBS="user32.lib gdi32.lib winmm.lib advapi32.lib shell32.lib ws2_32.lib ole32.lib"

# build <output> <extra clang flags> <sources...> -- <extra lld-link arguments...>
build() {
    out=$1 flags=$2
    shift 2
    obj=$OUT/obj/$(basename "$out")
    rm -rf "$obj"
    mkdir -p "$obj"
    objs=
    while [ "$1" != -- ]; do
        o=$obj/$(basename "$1" .c).obj
        clang $CFLAGS $flags -c "$1" -o "$o"
        objs="$objs $o"
        shift
    done
    shift
    lld-link -nologo -out:"$out" $LDFLAGS $objs "$@" $SYSLIBS
    rm -f "${out%.*}.lib" "${out%.*}.exp"
}

build $OUT/LANCommander.Interposer.Plugin.LegendsOfMightAndMagic.dll "" src/interposer_plugin.c $CORE -- \
    -export:InterposerPluginInit=_InterposerPluginInit@4

if [ "${INTERPOSER:-1}" = 0 ]; then
    echo "INTERPOSER=0: dinput.dll and lommpatch.asi not built"
    exit 0
fi

# the Interposer: its static library, the libraries it was built with, and YY-Thunks (the MSVC runtime on XP)
INTERPOSER_DIR=${INTERPOSER_DIR:-third_party/LANCommander.Interposer}
INTERPOSER_OUT=$INTERPOSER_DIR/out/windows-x86
INTERPOSER_DEPS=$INTERPOSER_OUT/vcpkg_installed/x86-windows-static/lib
INTERPOSER_LIBS="-wholearchive:$INTERPOSER_OUT/lib/Release/LANCommander.Interposer.Static.lib
    $INTERPOSER_DEPS/yaml-cpp.lib $INTERPOSER_DEPS/enet.lib $INTERPOSER_DEPS/opus.lib $INTERPOSER_DEPS/minhook.x32.lib
    winhttp.lib iphlpapi.lib"
YY_THUNKS=$(ls "$INTERPOSER_DIR"/build/YY-Thunks/*/objs/x86/YY_Thunks_for_WinXP.obj | tail -1)
# what XP needs of a DLL built with the current MSVC runtime, as the Interposer's own (its build/Compatibility.cmake)
EMBEDDED_LDFLAGS="-subsystem:windows,5.01 -entry:DllMainCRTStartupForYY_Thunks
    -alternatename:_YY_ThunksOriginalDllMainCRTStartup@12=__DllMainCRTStartup@12 $YY_THUNKS"

build $OUT/dinput.dll "-DLM_INTERPOSER_EMBEDDED -DINTERPOSER_STATIC" src/dinput_proxy.c $CORE -- \
    -def:src/dinput.def $EMBEDDED_LDFLAGS $INTERPOSER_LIBS
build $OUT/lommpatch.asi "-DLM_INTERPOSER_EMBEDDED -DINTERPOSER_STATIC" src/asi.c $CORE -- \
    $EMBEDDED_LDFLAGS $INTERPOSER_LIBS
